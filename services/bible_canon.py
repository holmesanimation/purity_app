def normalize_ref(book_key: str, chapter: int, verse: int) -> str:
    """Return a stable storage key, e.g. "john_3_16"."""
    return f"{book_key}_{chapter}_{verse}"


def display_ref(book_key: str, chapter: int, verse: int) -> str:
    """Return a human-readable reference, e.g. "John 3:16"."""
    display = BOOK_DISPLAY.get(book_key, book_key.capitalize())
    return f"{display} {chapter}:{verse}"
